"""SmartRoutine activities, versioned daily plans and replanning."""

from __future__ import annotations

from datetime import date
from http import HTTPStatus
from typing import Annotated, Any
from uuid import UUID

from fastapi import APIRouter, Depends, Query, Response

from app.api.deps import (
    AirServiceDep,
    CurrentProfile,
    GeminiDep,
    RequestIdDep,
    SessionDep,
    SettingsDep,
    session_rate_limit,
)
from app.schemas.envelope import Envelope, envelope
from app.schemas.routines import (
    ActivityList,
    RoutineActivity,
    RoutineActivityChange,
    RoutineActivityCreate,
    RoutineActivityUpdate,
    RoutineGenerateRequest,
    RoutineHistory,
    RoutineItemUpdate,
    RoutinePlan,
    RoutineReplanRequest,
)
from app.services import routine_service

router = APIRouter(prefix="/routines", tags=["routines"])

_ERRORS: dict[int | str, dict[str, Any]] = {
    HTTPStatus.UNAUTHORIZED: {"description": "Missing or invalid bearer token."},
    HTTPStatus.NOT_FOUND: {
        "description": "No household, activity, routine or routine item was found."
    },
    HTTPStatus.CONFLICT: {
        "description": (
            "The routine version is superseded, or it was generated by an "
            "earlier engine version."
        )
    },
    HTTPStatus.UNPROCESSABLE_ENTITY: {
        "description": (
            "Invalid activity input, overlapping fixed activities, missing "
            "household data, or a forecast that does not cover the date."
        )
    },
    HTTPStatus.TOO_MANY_REQUESTS: {"description": "Session rate limit exceeded."},
    HTTPStatus.SERVICE_UNAVAILABLE: {
        "description": "Forecast or observation data is unavailable."
    },
}


# -- activity preferences --------------------------------------------------


@router.get(
    "/activities",
    response_model=Envelope[ActivityList],
    summary="List SmartRoutine activities",
    description=(
        "Returns the session household's active activities. Cancelled "
        "activities are kept for plan history but are not listed."
    ),
    responses=_ERRORS,
)
async def list_activities(
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
) -> Envelope[ActivityList]:
    items = await routine_service.list_activities(session, profile)
    return envelope(ActivityList(items=items), request_id)


@router.post(
    "/activities",
    response_model=Envelope[RoutineActivity],
    status_code=HTTPStatus.CREATED,
    summary="Add an activity",
    description=(
        "Validates duration, preferred/earliest/latest start, indoor/outdoor "
        "category consistency, member ownership and fixed-activity overlaps."
    ),
    responses=_ERRORS,
)
async def create_activity(
    payload: RoutineActivityCreate,
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
    _limit: None = Depends(session_rate_limit("routine-activity-write")),
) -> Envelope[RoutineActivity]:
    activity = await routine_service.create_activity(session, profile, payload)
    return envelope(activity, request_id)


@router.put(
    "/activities/{activity_id}",
    response_model=Envelope[RoutineActivity],
    summary="Update an activity preference",
    responses=_ERRORS,
)
async def update_activity(
    activity_id: UUID,
    payload: RoutineActivityUpdate,
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
    _limit: None = Depends(session_rate_limit("routine-activity-write")),
) -> Envelope[RoutineActivity]:
    activity = await routine_service.update_activity(
        session, profile, activity_id, payload
    )
    return envelope(activity, request_id)


@router.delete(
    "/activities/{activity_id}",
    status_code=HTTPStatus.NO_CONTENT,
    summary="Cancel an activity",
    description=(
        "Soft-deletes the activity so earlier plan versions remain readable. "
        "Generate a new plan to remove it from the schedule."
    ),
    responses=_ERRORS,
)
async def delete_activity(
    activity_id: UUID,
    profile: CurrentProfile,
    session: SessionDep,
    _limit: None = Depends(session_rate_limit("routine-activity-write")),
) -> Response:
    await routine_service.delete_activity(session, profile, activity_id)
    return Response(status_code=HTTPStatus.NO_CONTENT)


# -- plans -----------------------------------------------------------------


@router.get(
    "/history",
    response_model=Envelope[RoutineHistory],
    summary="List routine versions",
    description=(
        "Returns every stored version for the session household, newest first. "
        "Active and superseded versions are both listed."
    ),
    responses=_ERRORS,
)
async def routine_history(
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
    plan_date: Annotated[
        date | None, Query(alias="date", description="Filter to one plan date.")
    ] = None,
    limit: Annotated[int, Query(ge=1, le=routine_service.HISTORY_MAX)] = (
        routine_service.HISTORY_DEFAULT
    ),
    offset: Annotated[int, Query(ge=0)] = 0,
) -> Envelope[RoutineHistory]:
    history = await routine_service.history(
        session,
        profile,
        plan_date=plan_date,
        limit=limit,
        offset=offset,
    )
    return envelope(history, request_id)


@router.get(
    "",
    response_model=Envelope[RoutinePlan],
    summary="Read the active routine",
    description=(
        "Returns the active stored plan for the date (default: today in the "
        "household timezone). Generation is explicit through POST /generate."
    ),
    responses=_ERRORS,
)
async def read_routine(
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
    plan_date: Annotated[
        date | None,
        Query(alias="date", description="Plan date in the household timezone."),
    ] = None,
) -> Envelope[RoutinePlan]:
    plan = await routine_service.get(session, profile, plan_date=plan_date)
    return envelope(plan, request_id)


@router.get(
    "/{routine_id}",
    response_model=Envelope[RoutinePlan],
    summary="Read a specific routine version",
    responses=_ERRORS,
)
async def read_routine_version(
    routine_id: UUID,
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
) -> Envelope[RoutinePlan]:
    plan = await routine_service.get(session, profile, routine_id=routine_id)
    return envelope(plan, request_id)


@router.post(
    "/generate",
    response_model=Envelope[RoutinePlan],
    summary="Generate a routine for a date",
    description=(
        "Runs the deterministic scheduling engine over the 48-hour forecast. "
        "Identical inputs return the active plan unless refresh is true. A new "
        "version is stored whenever the inputs or forecast change. No language "
        "model is used for scheduling."
    ),
    responses=_ERRORS,
)
async def generate_routine(
    payload: RoutineGenerateRequest,
    profile: CurrentProfile,
    session: SessionDep,
    air_service: AirServiceDep,
    settings: SettingsDep,
    gemini: GeminiDep,
    request_id: RequestIdDep,
    _limit: None = Depends(session_rate_limit("routine-generate")),
) -> Envelope[RoutinePlan]:
    plan = await routine_service.generate(
        session,
        profile,
        plan_date=payload.date,
        refresh=payload.refresh,
        air_service=air_service,
        settings=settings,
        gemini=gemini,
    )
    return envelope(plan, request_id)


@router.post(
    "/{routine_id}/replan",
    response_model=Envelope[RoutinePlan],
    summary="Replan the active routine",
    description=(
        "Re-reads the forecast and regenerates from the current activities. "
        "Fixed activities and saved activity preferences are preserved. "
        "Identical inputs return the existing active version, so repeated "
        "requests do not create duplicates."
    ),
    responses=_ERRORS,
)
async def replan_routine(
    routine_id: UUID,
    payload: RoutineReplanRequest,
    profile: CurrentProfile,
    session: SessionDep,
    air_service: AirServiceDep,
    settings: SettingsDep,
    gemini: GeminiDep,
    request_id: RequestIdDep,
    _limit: None = Depends(session_rate_limit("routine-generate")),
) -> Envelope[RoutinePlan]:
    plan = await routine_service.replan(
        session,
        profile,
        routine_id=routine_id,
        plan_date=payload.date,
        air_service=air_service,
        settings=settings,
        gemini=gemini,
    )
    return envelope(plan, request_id)


@router.put(
    "/{routine_id}/activities/{activity_id}",
    response_model=Envelope[RoutinePlan],
    summary="Change one activity and regenerate the plan",
    description=(
        "Reschedule, change duration, mark fixed or cancel an activity. The "
        "change is saved as an activity preference and a new plan version is "
        "stored, so it survives later replanning. Other fixed activities are "
        "preserved."
    ),
    responses=_ERRORS,
)
async def change_routine_activity(
    routine_id: UUID,
    activity_id: UUID,
    payload: RoutineActivityChange,
    profile: CurrentProfile,
    session: SessionDep,
    air_service: AirServiceDep,
    settings: SettingsDep,
    gemini: GeminiDep,
    request_id: RequestIdDep,
    _limit: None = Depends(session_rate_limit("routine-generate")),
) -> Envelope[RoutinePlan]:
    plan = await routine_service.update_routine_activity(
        session,
        profile,
        routine_id=routine_id,
        activity_id=activity_id,
        change=payload,
        air_service=air_service,
        settings=settings,
        gemini=gemini,
    )
    return envelope(plan, request_id)


@router.patch(
    "/{routine_id}/items/{block_id}",
    response_model=Envelope[RoutinePlan],
    summary="Mark a routine item done or skipped",
    responses=_ERRORS,
)
async def update_routine_item(
    routine_id: UUID,
    block_id: str,
    payload: RoutineItemUpdate,
    profile: CurrentProfile,
    session: SessionDep,
    request_id: RequestIdDep,
    _limit: None = Depends(session_rate_limit("routine-update")),
) -> Envelope[RoutinePlan]:
    plan = await routine_service.update_item(
        session,
        profile,
        routine_id=routine_id,
        block_id=block_id,
        payload=payload,
    )
    return envelope(plan, request_id)
